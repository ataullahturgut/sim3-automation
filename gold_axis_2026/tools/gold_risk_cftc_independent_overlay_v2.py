"""Independent Gold Risk V2 - CFTC overlay, **research only**.

Usage: python gold_risk_cftc_independent_overlay_v2.py \
  --source-zip risk-overlay-source-artifact.zip \
  --cftc-csv CFTC_GC_SI_2023_2026_QUALITY_GATED.csv \
  --outdir gold-risk-v2
Source artifact: gold-market overlay official-price/GVZ/H10/H15 snapshot.
The CFTC CSV is generated by CFTC's official disaggregated historical ZIPs
using GC COMEX=088691 and SI COMEX=084691 and a publication-date quality gate.

Fits ONLY observed 2023-2024 dates for 2025 diagnostic; ONLY observed
2023-2025 dates for 2026 stress, no later than cutoff. This scores *anomaly*,
NOT directional crash odds, ANN model error odds, investment decisions,
or validated live actionable data. GLD is quarantined for first publication
time; CME/SLV are absent, never filled with zero.

All workflow scheduling remains manual-only.
"""
import argparse,csv,hashlib,json,zipfile
from datetime import date
from pathlib import Path
from bisect import bisect_right
from gold_risk_release_clock_v8 import cftc_conservative_is_available
import numpy as np
from sklearn.preprocessing import RobustScaler
from sklearn.ensemble import IsolationForest
from gold_forecast_risk_overlay_2023_2026_v1 import data as old_features

FAMILIES={"BASE_14":list(range(14)),
          "BASE_14_PLUS_CFTC_7":list(range(21)),
          "CFTC_7_ONLY":list(range(14,21)),
          "METAL_GVZ_10":list(range(10))}
CODE={"GC":"088691","SI":"084691"}
def gate(condition,why):
    if not condition:raise ValueError("GOLD_RISK_CFTC_V2_BLOCK:"+why)
def load_cftc(path):
    with open(path,newline="",encoding="utf-8") as f:raw=list(csv.DictReader(f))
    gate(len(raw)==398,"EXPECTED_398_PUBLISHED_2023_2026_RECORDS")
    out={k:[] for k in CODE}
    seen=set()
    for q in raw:
        k=q["market"];d=q["report_date"];a=q["earliest_conservative_usable_date"]
        gate(k in CODE and q["contract_code"].zfill(6)==CODE[k],"WRONG_CFTC_CONTRACT")
        gate((d,k) not in seen and a>d,"CFTC_DUPLICATE_OR_EARLY_USE")
        seen.add((d,k))
        gate(q["release_status"] in
             ("UNVERIFIED_NORMAL_WEEK_7D_LAG_PROXY","PUBLISHED_CFTC_9147_25_PUB_PLUS1D"),
             "CFTC_PUBLICATION_UNKNOWN")
        oi=float(q["open_interest"])
        gate(oi>0,"CFTC_BAD_OPEN_INTEREST")
        out[k].append({"report":d,"available":a,"net_oi":float(q["mm_net_fraction_oi"]),
                       "short_oi":float(q["managed_money_short"])/oi,
                       "publication_quality":q["release_status"]})
    for k in out:
        out[k].sort(key=lambda r:r["report"])
        gate(len(out[k])==199,"CFTC_YEARLY_COVERAGE_"+k)
    gate([x["report"] for x in out["GC"]]==[x["report"] for x in out["SI"]],"CFTC_PAIR_ALIGNMENT")
    gate(next(x for x in out["GC"] if x["report"]=="2025-09-30")["available"]==
         "2025-11-20","2025_SHUTDOWN_CFTC_FUTURE_LEAK")
    return out,hashlib.sha256(Path(path).read_bytes()).hexdigest()
def merge(base,weekly):
    dates=[q["report"] for q in weekly["GC"]]
    out=[]
    for q in base:
        d=q["origin"];i=bisect_right(dates,d)-1
        while i>=0 and not cftc_conservative_is_available(weekly["GC"][i]["available"],d):i-=1
        if i<4:continue
        gc=weekly["GC"];si=weekly["SI"]
        cur=gc[i]
        gate(cftc_conservative_is_available(cur["available"],d) and cftc_conservative_is_available(si[i]["available"],d),"UNPUBLISHED_CFTC_FEATURE")
        staleness=(date.fromisoformat(d)-date.fromisoformat(cur["available"])).days
        if staleness>21:continue
        getgc=lambda j:gc[j]["net_oi"]
        getsi=lambda j:si[j]["net_oi"]
        features=[
            getgc(i),getsi(i),getgc(i)-getgc(i-1),
            getgc(i)-getgc(i-4),getsi(i)-getsi(i-4),
            getgc(i)-getsi(i),gc[i]["short_oi"]]
        gate(len(q["features"])==14 and len(features)==7,"UNEXPECTED_FEATURE_SCHEMA")
        item=dict(q)
        item["features"]=q["features"]+features
        item["cftc_report_day"]=cur["report"]
        item["cftc_available_day"]=cur["available"]
        item["cftc_quality"]=cur["publication_quality"]
        item["cftc_staleness_days"]=staleness
        out.append(item)
    gate(len(out)>850 and any(x["origin"]=="2026-01-29" for x in out),
         "MISSING_ALIGNED_MARKET_ORIGIN")
    gate(all(cftc_conservative_is_available(x["cftc_available_day"],x["origin"]) and
        x["usd_release_date"]<=x["origin"] and
        x["yield_last_observation"]<x["origin"] for x in out),"FEATURE_LOOKAHEAD")
    return out
def score(data):
    results={};daily=[]
    for period,through,first,last in [
        ("2025","2024-12-31","2025-01-01","2025-12-31"),
        ("2026","2025-12-31","2026-01-01","2026-09-21")]:
        train=[x for x in data if x["target5_mature"]<=through]
        test=[x for x in data if first<=x["origin"]<=last]
        gate(len(train)>400 and len(test)>130,"INSUFFICIENT_DATA_"+period)
        results[period]={}
        for family,idx in FAMILIES.items():
            a=np.array([x["features"] for x in train],float)[:,idx]
            b=np.array([x["features"] for x in test],float)[:,idx]
            gate(np.isfinite(a).all() and np.isfinite(b).all(),"NONFINITE_INPUT")
            scaler=RobustScaler().fit(a)
            model=IsolationForest(n_estimators=200,max_samples=min(len(train),256),
                contamination="auto",random_state=1701,n_jobs=1).fit(scaler.transform(a))
            tr=-model.score_samples(scaler.transform(a))
            tt=-model.score_samples(scaler.transform(b))
            yellow,red=np.quantile(tr,[.90,.95])
            items=[]
            for src,risk in zip(test,tt):
                level="RED" if risk>=red else "YELLOW" if risk>=yellow else "NORMAL"
                row={
                    "origin":src["origin"],"period":period,"family":family,
                    "risk_score":float(risk),"level":level,
                    "first_target":src["first_target"],"target_mature":src["target5_mature"],
                    "cftc_report_day":src["cftc_report_day"],
                    "cftc_available_day":src["cftc_available_day"],
                    "cftc_quality":src["cftc_quality"],
                    "xau_usd_oz":src["xau_price"],
                    "next_day_return_pct":src["next_day_return_pct"],
                    "min_next5_return_pct":src["min_next5_return_pct"],
                    "next_day_drop3":src["next_day_drop3"],
                    "next5_drop5":src["next5_drop5"],
                    "next5_large_abs5":src["next5_large_abs5"],
                    "threshold_yellow":float(yellow),"threshold_red":float(red)}
                items.append(row);daily.append(row)
            summary={"train_n":len(train),"score_n":len(test),
                     "red_alert_n":sum(r["level"]=="RED" for r in items),
                     "yellow_alert_n":sum(r["level"]=="YELLOW" for r in items)}
            for label in ["next_day_drop3","next5_drop5","next5_large_abs5"]:
                for name,levels in [("red",{"RED"}),("red_or_yellow",{"YELLOW","RED"})]:
                    alarms=[q for q in items if q["level"] in levels]
                    hits=[q for q in alarms if q[label]]
                    events=[q for q in items if q[label]]
                    summary[label+"_"+name]={
                        "event_origin_days":len(events),"alarm_origin_days":len(alarms),
                        "hit_origin_days":len(hits),"miss_origin_days":len(events)-len(hits),
                        "false_alarm_origin_days":len(alarms)-len(hits),
                        "precision":len(hits)/len(alarms) if alarms else None,
                        "recall":len(hits)/len(events) if events else None}
            results[period][family]=summary
            print("GOLD_RISK_CFTC_V2",period,family,json.dumps(summary,sort_keys=True))
    return results,daily
def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--source-zip",required=True)
    ap.add_argument("--cftc-csv",required=True)
    ap.add_argument("--outdir",required=True)
    args=ap.parse_args();Path(args.outdir).mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(args.source_zip) as z:
        source=json.loads(z.read("risk-overlay-source.json"))
    cftc,h=load_cftc(args.cftc_csv)
    full=merge(old_features(source),cftc)
    stats,daily=score(full)
    with open(Path(args.outdir)/"daily_issues.csv","w",newline="") as f:
        writer=csv.DictWriter(f,fieldnames=list(daily[0]));writer.writeheader();writer.writerows(daily)
    manifest={"research_only":True,"not_deployed":True,
      "ann_error_probability_validated":False,"nextday_crash_probability_validated":False,
      "source_firstprint_verified":False,"cftc_regular_week_lag_proxy_not_certified":True,
      "gold_2026_feb27_bad_price_quarantined":True,
      "missing_GLD_CME_SLV_not_imputed":True,
      "CFTC_SHA256":h,"model":"Unsupervised IsolationForest, RobustScaler; fit-only fixed .90/.95 score quantiles",
      "families":FAMILIES,"train_2025":"2023-2024","train_2026":"2023-2025",
      "scores":stats,"aligned_origins":len(full)}
    Path(args.outdir,"audit.json").write_text(json.dumps(manifest,indent=2,allow_nan=False)+"\n")
    gate(stats["2025"]["BASE_14_PLUS_CFTC_7"]["next_day_drop3_red"]["hit_origin_days"]==3,
         "2025_NOT_REPRODUCED")
    gate(stats["2026"]["BASE_14_PLUS_CFTC_7"]["next_day_drop3_red"]["hit_origin_days"]==4,
         "2026_NOT_REPRODUCED")
    print("GOLD_RISK_V2_REPRODUCTION_PASS_NO_DATABASE_OR_MAIN_MODEL_WRITE")
if __name__=="__main__":main()
