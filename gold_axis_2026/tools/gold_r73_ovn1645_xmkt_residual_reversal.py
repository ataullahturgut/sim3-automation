import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PANEL = ROOT / "GOLD_R73_20261012_OVN1645_XMKT_PANEL_LOGRET_E5.csv"
R67 = ROOT / "GOLD_R67_20261012_H3_AS_DAY_AND_OVN_CONDITIONER_2023_2026_ROWS.csv"
OUT_ROWS = ROOT / "GOLD_R73_20261012_OVN1645_XMKT_RESIDUAL_ROWS.csv"
OUT_SUMMARY = ROOT / "GOLD_R73_20261012_OVN1645_XMKT_RESIDUAL_SUMMARY.json"

ALPHA = 10.0          # ridge penalty on standardized design (sum-of-squares scale)
WINDOW = 250          # most recent prior complete weekdays
MIN_TRAIN = 60
DEV_YEARS = (2023, 2024)
N_BOOT = 2000
SEED = 20261012


# ---------------------------------------------------------------- statistics
def binom_sf(k, n, p=0.5):
    """P(X >= k), X ~ Bin(n, p), exact."""
    return float(sum(math.comb(n, i) * p**i * (1 - p) ** (n - i) for i in range(k, n + 1)))


def norm_sf(z):
    return 0.5 * math.erfc(z / math.sqrt(2))


def wilson(k, n, z=1.959964):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (c - h, c + h)


def bal_acc(y, p):
    y, p = np.asarray(y), np.asarray(p)
    up = y == 1
    dn = y == 0
    ru = float((p[up] == 1).mean()) if up.any() else float("nan")
    rd = float((p[dn] == 0).mean()) if dn.any() else float("nan")
    return (ru + rd) / 2, ru, rd


def ols_hc3(y, X):
    X = np.column_stack([np.ones(len(y)), X])
    XtX_inv = np.linalg.inv(X.T @ X)
    b = XtX_inv @ X.T @ y
    r = y - X @ b
    h = np.einsum("ij,jk,ik->i", X, XtX_inv, X)
    meat = X.T @ (X * (r / (1 - h))[:, None] ** 2)
    se = np.sqrt(np.diag(XtX_inv @ meat @ XtX_inv))
    return b, se


# ---------------------------------------------------------------- model
def rolling_residuals(df, w):
    g, f = f"g{w}", [f"zn{w}", f"nq{w}", f"cl{w}"]
    train_ok = df[[g] + f].notna().all(axis=1)
    tr = df.loc[train_ok, ["decision_date", g] + f].reset_index(drop=True)
    out = {}
    for idx, row in df.iterrows():
        if not train_ok[idx]:
            continue
        past = tr[tr.decision_date < row.decision_date].tail(WINDOW)
        if len(past) < MIN_TRAIN:
            continue
        X = past[f].to_numpy(float)
        y = past[g].to_numpy(float)
        mu, sd = X.mean(0), X.std(0)
        Z = (X - mu) / sd
        b = np.linalg.solve(Z.T @ Z + ALPHA * np.eye(3), Z.T @ (y - y.mean()))
        z_t = (row[f].to_numpy(float) - mu) / sd
        fitted = float(y.mean() + z_t @ b)
        out[idx] = (fitted, float(row[g]) - fitted, len(past), b.tolist())
    return out


def build_rows(df, w):
    res = rolling_residuals(df, w)
    tgt = (df.isodow <= 4) & df.ovn.notna() & (df.ovn != 0)
    rows = []
    for idx in df.index[tgt]:
        if idx not in res:
            continue
        r = df.loc[idx]
        fitted, e, ntr, b = res[idx]
        g = float(r[f"g{w}"])
        if e == 0 or g == 0:
            continue
        rows.append(dict(
            decision_date=r.decision_date.date().isoformat(), year=int(r.year), xau_source=r.xau_source,
            window=f"W{w}", g=g, fitted=fitted, resid=e, n_train=ntr,
            b_zn=b[0], b_nq=b[1], b_cl=b[2],
            ovn=float(r.ovn), lc=float(r.lc), sc=float(r.sc), y=int(r.ovn > 0),
            p_resid=int(e < 0), p_rev=int(g < 0), p_mom=int(g > 0),
        ))
    return pd.DataFrame(rows)


# ---------------------------------------------------------------- evaluation
def rule_metrics(y, p, ovn, lc, sc):
    y, p = np.asarray(y), np.asarray(p)
    n = len(y)
    k = int((y == p).sum())
    ba, ru, rd = bal_acc(y, p)
    lo, hi = wilson(k, n)
    signed = np.where(p == 1, ovn, -ovn)
    crossed = np.where(p == 1, lc, sc)
    return dict(n=n, correct=k, acc=k / n, acc_wilson95=[lo, hi], ba=ba, up_recall=ru, down_recall=rd,
                pred_up=int(p.sum()), mean_signed_mid_bp=float(signed.mean() / 10),
                sum_signed_mid_bp=float(signed.sum() / 10), mean_dukascopy_crossed_bp=float(crossed.mean() / 10))


def mcnemar(y, pa, pb):
    a_ok, b_ok = (np.asarray(pa) == y), (np.asarray(pb) == y)
    rescue = int((a_ok & ~b_ok).sum())
    brk = int((~a_ok & b_ok).sum())
    p = binom_sf(rescue, rescue + brk) if rescue + brk else float("nan")
    return dict(a_right_b_wrong=rescue, a_wrong_b_right=brk, net=rescue - brk, one_sided_p=p)


def block_boot_ba_diff(d, col_a, col_b):
    rng = np.random.default_rng(SEED)
    months = d.decision_date.str[:7].to_numpy()
    keys = np.unique(months)
    groups = [np.where(months == m)[0] for m in keys]
    diffs = []
    y = d.y.to_numpy()
    a, b = d[col_a].to_numpy(), d[col_b].to_numpy()
    for _ in range(N_BOOT):
        idx = np.concatenate([groups[i] for i in rng.integers(0, len(groups), len(groups))])
        diffs.append(bal_acc(y[idx], a[idx])[0] - bal_acc(y[idx], b[idx])[0])
    diffs = np.array(diffs)
    return dict(observed=bal_acc(y, a)[0] - bal_acc(y, b)[0],
                ci95=[float(np.quantile(diffs, 0.025)), float(np.quantile(diffs, 0.975))],
                p_le_0=float((diffs <= 0).mean()))


def spearman(a, b):
    return float(pd.Series(a).rank().corr(pd.Series(b).rank()))


def evaluate(rows, eligible_nights):
    out = {"per_year": {}, "dev": {}}
    rules = {"R_RESID": "p_resid", "R_REV": "p_rev", "R_MOM": "p_mom"}
    groups = [(str(yr), rows[rows.year == yr]) for yr in sorted(rows.year.unique())]
    groups.append(("DEV_2023_2024", rows[rows.year.isin(DEV_YEARS)]))
    for name, d in groups:
        if d.empty:
            continue
        y = d.y.to_numpy()
        m = {"n": len(d), "eligible_target_nights": int(eligible_nights.get(name, 0)),
             "up_rate": float(y.mean())}
        m["coverage"] = m["n"] / m["eligible_target_nights"] if m["eligible_target_nights"] else None
        for rn, col in rules.items():
            m[rn] = rule_metrics(y, d[col], d.ovn, d.lc, d.sc)
        m["ALWAYS_UP"] = rule_metrics(y, np.ones(len(d), int), d.ovn, d.lc, d.sc)
        m["ALWAYS_DOWN"] = rule_metrics(y, np.zeros(len(d), int), d.ovn, d.lc, d.sc)
        m["RESID_vs_REV"] = mcnemar(y, d.p_resid, d.p_rev)
        m["resid_rev_disagree_n"] = int((d.p_resid != d.p_rev).sum())
        m["spearman_resid_ovn"] = spearman(d.resid, d.ovn)
        m["spearman_g_ovn"] = spearman(d.g, d.ovn)
        m["binom_p_resid_acc_gt_50"] = binom_sf(m["R_RESID"]["correct"], len(d))
        m["mean_abs_ovn_bp"] = float(d.ovn.abs().mean() / 10)
        m["mean_dukascopy_roundtrip_cost_bp"] = float(((d.ovn - d.lc) + (-d.ovn - d.sc)).mean() / 20)
        out["per_year"][name] = m
    dev = rows[rows.year.isin(DEV_YEARS)]
    if len(dev):
        b, se = ols_hc3(dev.ovn.to_numpy(float), dev[["fitted", "resid"]].to_numpy(float))
        t = b / se
        out["dev"]["ols_ovn_on_fitted_resid_hc3"] = {
            "coef": dict(zip(["const", "fitted", "resid"], b.tolist())),
            "se": dict(zip(["const", "fitted", "resid"], se.tolist())),
            "t": dict(zip(["const", "fitted", "resid"], t.tolist())),
            "one_sided_p_resid_lt_0": norm_sf(-t[2]),
            "diff_resid_minus_fitted": float(b[2] - b[1]),
        }
        b2, se2 = ols_hc3(dev.ovn.to_numpy(float), dev[["g"]].to_numpy(float))
        out["dev"]["ols_ovn_on_g_hc3"] = {"coef_g": float(b2[1]), "se": float(se2[1]),
                                          "one_sided_p_lt_0": norm_sf(-b2[1] / se2[1])}
        b3, se3 = ols_hc3(dev.ovn.to_numpy(float), dev[["g", "resid"]].to_numpy(float))
        out["dev"]["ols_ovn_on_g_and_resid_hc3"] = {
            "coef": dict(zip(["const", "g", "resid"], b3.tolist())),
            "t": dict(zip(["const", "g", "resid"], (b3 / se3).tolist()))}
        out["dev"]["block_boot_ba_diff_resid_minus_rev"] = block_boot_ba_diff(dev, "p_resid", "p_rev")
        q = pd.qcut(dev.resid, 5, labels=False)
        out["dev"]["resid_quintiles"] = [
            {"q": int(i), "n": int((q == i).sum()), "mean_resid_bp": float(dev.resid[q == i].mean() / 10),
             "mean_next_ovn_bp": float(dev.ovn[q == i].mean() / 10), "up_rate": float(dev.y[q == i].mean())}
            for i in range(5)]
    return out


def r67_compare(rows):
    r67 = pd.read_csv(R67)
    r67 = r67[r67.clock == "OVN"][["day", "h3bit", "new_pred", "y"]].rename(
        columns={"day": "decision_date", "y": "y_r67_histdata"})
    m = rows.merge(r67, on="decision_date", how="inner")
    out = {}
    for name, d in [(str(yr), m[m.year == yr]) for yr in sorted(m.year.unique())] + \
                   [("DEV_2023_2024", m[m.year.isin(DEV_YEARS)])]:
        if d.empty:
            continue
        y = d.y.to_numpy()
        out[name] = {
            "matched_n": len(d),
            "label_agreement_evduka_vs_r67_histdata": float((d.y == d.y_r67_histdata).mean()),
            "R_RESID": rule_metrics(y, d.p_resid, d.ovn, d.lc, d.sc),
            "R_REV": rule_metrics(y, d.p_rev, d.ovn, d.lc, d.sc),
            "R67_new_pred": rule_metrics(y, d.new_pred, d.ovn, d.lc, d.sc),
            "R67_h3bit": rule_metrics(y, d.h3bit, d.ovn, d.lc, d.sc),
            "RESID_vs_R67_new_pred": mcnemar(y, d.p_resid, d.new_pred),
            "RESID_vs_R67_h3bit": mcnemar(y, d.p_resid, d.h3bit),
            "r67_in_sample_note": "R67 new_pred was fitted on 2023-24 -> DEV rows are in-sample for R67",
        }
    return out


def holm(pvals):
    order = sorted(range(len(pvals)), key=lambda i: pvals[i])
    adj, running = [0.0] * len(pvals), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(pvals) - rank) * pvals[i]))
        adj[i] = running
    return adj


def main():
    df = pd.read_csv(PANEL, parse_dates=["decision_date"])
    df["year"] = df.decision_date.dt.year
    df["isodow"] = df.decision_date.dt.isocalendar().day.astype(int)
    tgt = (df.isodow <= 4) & df.ovn.notna()
    elig = {str(k): int(v) for k, v in df[tgt].groupby("year").size().items()}
    elig["DEV_2023_2024"] = elig.get("2023", 0) + elig.get("2024", 0)

    summary = {"prereg_commit": "2371b588f51422196f9341fe5605c5a97f3d43a5",
               "params": dict(alpha=ALPHA, window=WINDOW, min_train=MIN_TRAIN, dev_years=DEV_YEARS,
                              n_boot=N_BOOT, seed=SEED),
               "eligible_target_nights_mon_thu": elig, "windows": {}}
    all_rows = []
    for w in (7, 3):
        rows = build_rows(df, w)
        all_rows.append(rows)
        ev = evaluate(rows, elig)
        ev["r67_matched"] = r67_compare(rows)
        summary["windows"][f"W{w}"] = ev

    p_w7 = summary["windows"]["W7"]["per_year"]["DEV_2023_2024"]["binom_p_resid_acc_gt_50"]
    p_w3 = summary["windows"]["W3"]["per_year"]["DEV_2023_2024"]["binom_p_resid_acc_gt_50"]
    h7, h3 = holm([p_w7, p_w3])
    dev7 = summary["windows"]["W7"]["per_year"]["DEV_2023_2024"]
    H1 = h7 < 0.05 and dev7["R_RESID"]["ba"] > 0.5
    H2 = dev7["RESID_vs_REV"]["one_sided_p"] < 0.05
    ols = summary["windows"]["W7"]["dev"]["ols_ovn_on_fitted_resid_hc3"]
    H3 = ols["coef"]["resid"] < 0 and ols["one_sided_p_resid_lt_0"] < 0.05
    if H1 and H2 and H3:
        verdict = "CONTINUE"
    elif H1 and H3:
        verdict = "RAW-REVERSAL-ONLY"
    elif not H1:
        verdict = "REJECT"
    else:
        verdict = "INCONCLUSIVE / MORE DATA"
    summary["gates"] = {"H1_holm_p_W7": h7, "H1_holm_p_W3": h3, "H1": H1, "H2": H2, "H3": H3,
                        "verdict_primary_W7": verdict}
    pd.concat(all_rows).to_csv(OUT_ROWS, index=False, float_format="%.4f")
    OUT_SUMMARY.write_text(json.dumps(summary, indent=1, default=float))
    json.dump(summary["gates"], sys.stdout, indent=1)
    print()


if __name__ == "__main__":
    main()
