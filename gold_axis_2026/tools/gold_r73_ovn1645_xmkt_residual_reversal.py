"""R73 — OVN 16:45 -> next calendar day 09:00 TR: cross-market (ZN/NQ/CL) residual reversal.

Implements exactly the rules frozen in
gold_axis_2026/GOLD_R73_20261012_OVN1645_CROSSMARKET_RESIDUAL_REVERSAL_PREREG.md (commit 2371b588).

Input panel (derived log-returns x 1e5, no raw prices):
  gold_axis_2026/GOLD_R73_20261012_OVN1645_XMKT_PANEL_LOGRET_E5.csv
regenerated by gold_axis_2026/sql/gold_r73_ovn1645_xmkt_panel.sql (Neon project "Gold Control").
Comparator rows: gold_axis_2026/GOLD_R67_20261012_H3_AS_DAY_AND_OVN_CONDITIONER_2023_2026_ROWS.csv

Only numpy/pandas are required.
"""
import json
